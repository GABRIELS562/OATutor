/**
 * Seed the database with video data
 */
export async function seedVideoLibrary(db) {
    console.debug('Seeding video library...');

    // Add all videos
    for (const video of SEED_VIDEOS) {
        await db.addVideo(video);
    }

    // Add playlists
    for (const playlist of SEED_PLAYLISTS) {
        db.run(
            `INSERT OR REPLACE INTO video_playlists
             (id, title, description, subject, grade, channel_name, video_ids, sort_order)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
            [
                playlist.id,
                playlist.title,
                playlist.description,
                playlist.subject,
                playlist.grade,
                playlist.channel_name,
                JSON.stringify(playlist.video_ids),
                playlist.sort_order,
            ]
        );
    }

    console.debug(`Seeded ${SEED_VIDEOS.length} videos and ${SEED_PLAYLISTS.length} playlists`);
}

